/*
 * BresenhamCircle.h
 * -----------------
 * Bresenham Circle Drawing Algorithm with 8-way symmetry.
 *
 * Algorithm based on the course notes:
 *
 * Start with:
 *   x = 0
 *   y = r
 *
 * Initial decision variable:
 *   d = 3 - 2r
 *
 * At each step:
 *   Plot the current point and its 7 symmetric reflections
 *   Test d:
 *     If d < 0:
 *       d = d + 4x + 6
 *       (move only in x direction)
 *     Else:
 *       d = d + 4(x - y) + 10
 *       y = y - 1
 *       (move in both x and y directions)
 *   x = x + 1
 *   Continue while x < y
 *
 * 8-WAY SYMMETRY:
 * From a single calculated point (x,y), we get all 8 octant points:
 *   ( x,  y)   ( y,  x)
 *   (-x,  y)   (-y,  x)
 *   (-x, -y)   (-y, -x)
 *   ( x, -y)   ( y, -x)
 *
 * This means we only need to calculate points in one octant
 * (from 0 to 45 degrees) and reflect to get the full circle.
 *
 * Algorithm implementations are based on the algorithms taught in
 * the provided course notes.
 */

#ifndef GLIDE_BRESENHAM_CIRCLE_H
#define GLIDE_BRESENHAM_CIRCLE_H

#include "DrawingAlgorithm.h"
#include "../Common/MathUtils.h"
#include <cmath>
#include <sstream>

class BresenhamCircle : public DrawingAlgorithm {
private:
    Point center;       // Center of the circle
    float radiusVal;    // Radius r

    /*
     * Generate all 8 symmetric points from a single calculated point.
     *
     * The 8-way symmetry of a circle means that if (x,y) is on the circle,
     * then so are all reflections across the x-axis, y-axis, and y=x line:
     *   (x,y)  (y,x)  (-x,y)  (-y,x)  (-x,-y)  (-y,-x)  (x,-y)  (y,-x)
     *
     * Each point is offset by the circle's center.
     */
    std::vector<Point> getSymmetricPoints(int x, int y) const {
        int cx = MathUtils::roundToInt(center.x);
        int cy = MathUtils::roundToInt(center.y);

        std::vector<Point> points;
        points.push_back(Point((float)(cx + x), (float)(cy + y)));   // ( x,  y)
        points.push_back(Point((float)(cx + y), (float)(cy + x)));   // ( y,  x)
        points.push_back(Point((float)(cx - x), (float)(cy + y)));   // (-x,  y)
        points.push_back(Point((float)(cx - y), (float)(cy + x)));   // (-y,  x)
        points.push_back(Point((float)(cx - x), (float)(cy - y)));   // (-x, -y)
        points.push_back(Point((float)(cx - y), (float)(cy - x)));   // (-y, -x)
        points.push_back(Point((float)(cx + x), (float)(cy - y)));   // ( x, -y)
        points.push_back(Point((float)(cx + y), (float)(cy - x)));   // ( y, -x)
        return points;
    }

public:
    BresenhamCircle() : radiusVal(0) {
        algorithmName = "Bresenham Circle";
    }

    BresenhamCircle(Point center, float radius) : center(center), radiusVal(radius) {
        algorithmName = "Bresenham Circle";
    }

    void setParameters(Point c, float r) {
        center = c;
        radiusVal = r;
    }

    Point getCenter() const { return center; }
    float getRadius() const { return radiusVal; }

    std::string getDescription() const override {
        return "Bresenham's circle algorithm uses integer arithmetic and "
               "a decision variable d to efficiently determine which pixels "
               "to plot. It exploits 8-way symmetry: only one octant is "
               "calculated, and the rest are generated by reflection.";
    }

    /*
     * Execute the Bresenham Circle algorithm.
     *
     * This directly implements the course notes:
     *   x = 0, y = r
     *   d = 3 - 2r
     *   While x < y:
     *     Plot 8 symmetric points
     *     If d < 0: d = d + 4x + 6
     *     Else:     d = d + 4(x-y) + 10, y--
     *     x++
     */
    void execute() override {
        clear();

        int r = MathUtils::roundToInt(radiusVal);
        if (r <= 0) return;

        int x = 0;
        int y = r;

        /*
         * Initial decision variable from the notes:
         * d = 3 - 2r
         */
        int d = 3 - 2 * r;

        int iteration = 0;

        /*
         * Main loop: compute points in the first octant (x < y)
         * and generate all 8 symmetric points at each step.
         */
        while (x <= y) {
            iteration++;

            AlgorithmStep step;
            step.iteration = iteration;
            step.x = (float)x;
            step.y = (float)y;
            step.radius = (float)r;
            step.decisionVariable = (float)d;

            /* Generate all 8 symmetric points */
            std::vector<Point> symPoints = getSymmetricPoints(x, y);
            step.symmetricPoints = symPoints;
            step.plottedPoints = symPoints;

            /* Add all symmetric points to the full point list */
            for (const auto& p : symPoints) {
                allPoints.push_back(p);
            }

            /* Build explanation */
            std::ostringstream oss;
            if (iteration == 1) {
                oss << "Bresenham Circle: center = " << center.toString()
                    << ", radius = " << r << "\n";
                oss << "Start: x = 0, y = r = " << r << "\n";
                oss << "Initial d = 3 - 2r = 3 - " << (2*r) << " = " << d << "\n";
                oss << "Plot 8 symmetric points from (" << x << ", " << y << ")";
            } else {
                oss << "Iteration " << iteration << ": x = " << x
                    << ", y = " << y << ", d = " << d;
            }

            /* Decision logic */
            std::ostringstream decOss;
            int oldD = d;

            if (d < 0) {
                /*
                 * From the notes:
                 *   d < 0: move only in x direction
                 *   d = d + 4x + 6
                 */
                decOss << "d = " << d << " < 0\n";
                decOss << "Decision: move only in x direction\n";
                d = d + 4 * x + 6;
                decOss << "d = " << oldD << " + 4*" << x << " + 6 = " << d;
            } else {
                /*
                 * From the notes:
                 *   d >= 0: move in both x and y directions
                 *   d = d + 4(x - y) + 10
                 *   y = y - 1
                 */
                decOss << "d = " << d << " >= 0\n";
                decOss << "Decision: move in x AND decrease y\n";
                d = d + 4 * (x - y) + 10;
                decOss << "d = " << oldD << " + 4*(" << x << " - " << y
                       << ") + 10 = " << d << "\n";
                y = y - 1;
                decOss << "y decremented to " << y;
            }

            /* x always increments */
            x = x + 1;

            oss << "\n" << decOss.str();
            oss << "\nx incremented to " << x;

            /* Show the 8 symmetric points */
            oss << "\n\n8-way symmetric points:";
            oss << "\n  ( x,  y) = (" << step.x << ", " << step.y << ")";
            oss << "\n  ( y,  x) = (" << step.y << ", " << step.x << ")";
            oss << "\n  (-x,  y) = (" << -step.x << ", " << step.y << ")";
            oss << "\n  (-y,  x) = (" << -step.y << ", " << step.x << ")";
            oss << "\n  (-x, -y) = (" << -step.x << ", " << -step.y << ")";
            oss << "\n  (-y, -x) = (" << -step.y << ", " << -step.x << ")";
            oss << "\n  ( x, -y) = (" << step.x << ", " << -step.y << ")";
            oss << "\n  ( y, -x) = (" << step.y << ", " << -step.x << ")";

            step.explanation = oss.str();
            step.decision = (oldD < 0) ? "d < 0: x only" : "d >= 0: x and y";

            steps.push_back(step);
        }
    }
};

#endif // GLIDE_BRESENHAM_CIRCLE_H
